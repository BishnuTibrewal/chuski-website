import { readdir, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const publicDir = path.join(rootDir, 'public')
const outputFile = path.join(rootDir, 'src', 'data', 'productImageManifest.generated.js')

const supportedExtensions = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif'])

const productFolders = {
  'kacchi-kick': 'KacchaAam',
  'mango-mastani': 'PakkaAam',
  'lalchi-lychee': 'lalchilychee',
  'kala-khatta-kadak': 'kalakhatta',
  'orange-oye': 'orangeoye',
}

const homepageHeroFolder = 'Homepage'

const imageOrderOverrides = {
  PakkaAam: [
    'pakkaAam-2.png',
    'PakkaAam-1.png',
    'mangoMastani-4.png',
    'mixed-1.png',
    'PakkaAam-3.png',
  ],
  orangeoye: [
    'OrangeOye-1.png',
    'OrangeOye-3.png',
    'OrangeOye-2.png',
    'mixed-1.png',
  ],
  Homepage: [
    'kacchikairi-4.png',
    'OrangeOye-3.png',
    'kalakhatta-2.png',
    'LalchiLychee-2.png',
    'mangoMastani-4.png',
    'mixed-1.png',
    'OrangeOye-2.png',
    'kalakhatta-3.png',
  ],
}

const toPublicUrl = (folder, filename) =>
  `/${[folder, filename].map((segment) => encodeURIComponent(segment)).join('/')}`

const sortFilenames = (folder, filenames) => {
  const orderOverride = imageOrderOverrides[folder]

  if (!orderOverride) {
    return filenames.sort((a, b) => a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' }))
  }

  const orderRank = new Map(orderOverride.map((filename, index) => [filename, index]))

  return filenames.sort((a, b) => {
    const aRank = orderRank.get(a)
    const bRank = orderRank.get(b)

    if (aRank !== undefined && bRank !== undefined) {
      return aRank - bRank
    }

    if (aRank !== undefined) {
      return -1
    }

    if (bRank !== undefined) {
      return 1
    }

    return a.localeCompare(b, 'en', { numeric: true, sensitivity: 'base' })
  })
}

async function getProductImages(folder) {
  try {
    const entries = await readdir(path.join(publicDir, folder), { withFileTypes: true })

    const filenames = entries
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name)
      .filter((filename) => supportedExtensions.has(path.extname(filename).toLowerCase()))

    return sortFilenames(folder, filenames)
      .map((filename) => toPublicUrl(folder, filename))
  } catch (error) {
    if (error.code === 'ENOENT') {
      return []
    }

    throw error
  }
}

const manifest = {}

for (const [productId, folder] of Object.entries(productFolders)) {
  manifest[productId] = await getProductImages(folder)
}

const homepageHeroImages = await getProductImages(homepageHeroFolder)

const fileContents = `// This file is auto-generated by scripts/generate-product-image-manifest.mjs.
// Do not edit this file manually. Add images to public product folders and rerun the generator.

export const productImageManifest = ${JSON.stringify(manifest, null, 2)}

export const homepageHeroImages = ${JSON.stringify(homepageHeroImages, null, 2)}
`

await mkdir(path.dirname(outputFile), { recursive: true })
await writeFile(outputFile, fileContents)
